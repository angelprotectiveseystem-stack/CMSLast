def kb_tutorial_nav(section: str, step: int, total: int):
    rows = []
    nav = []
    if step > 0:
        nav.append(InlineKeyboardButton("◀️ قبلی", callback_data=f"htut_{section}_{step-1}"))
    if step < total - 1:
        nav.append(InlineKeyboardButton("▶️ بعدی", callback_data=f"htut_{section}_{step+1}"))
    if nav:
        rows.append(nav)
    rows.append([
        InlineKeyboardButton("🏠 فهرست راهنما", callback_data="menu_help"),
        InlineKeyboardButton("🔙 بازگشت", callback_data="back_main"),
    ])
    return InlineKeyboardMarkup(rows)


