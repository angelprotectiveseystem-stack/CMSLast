async def help_tutorial(update: Update, ctx: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    # Parse: htut_{section}_{step}
    parts = query.data.split("_")
    # htut + section_parts + step
    step = int(parts[-1])
    section = "_".join(parts[1:-1])

    if section not in TUTORIALS:
        await query.answer("بخش یافت نشد.", show_alert=True)
        return

    tut = TUTORIALS[section]
    steps = tut["steps"]
    total = len(steps)

    if step >= total:
        step = total - 1

    current = steps[step]
    progress = f"{'●' * (step + 1)}{'○' * (total - step - 1)}"

    text = (
        f"{current['text']}\n\n"
        f"━━━━━━━━━━━━━━━━━━━━\n"
        f"📍 {progress}  {step + 1} از {total}"
    )

    await query.edit_message_text(
        text,
        reply_markup=kb_tutorial_nav(section, step, total),
        parse_mode="Markdown"
    )
